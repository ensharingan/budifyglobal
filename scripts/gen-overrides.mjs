#!/usr/bin/env node
// Regenerates mechanical spelling overrides:
//   messages/overrides/en-US.json  (British → US spelling, from messages/en.json)
//   messages/overrides/de-CH.json  (ß → ss, from messages/de.json)
// Hand-written overrides in the same folder are never touched.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = (f) => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));

function transform(obj, fn, prefix = []) {
  // returns a sparse object containing only changed leaves
  const out = Array.isArray(obj) ? [] : {};
  let changed = false;
  for (const [k, v] of Object.entries(obj)) {
    if (k === '_meta') continue;
    let r;
    if (typeof v === 'string') { const n = fn(v); r = n !== v ? n : undefined; }
    else if (Array.isArray(v)) {
      const arr = v.map((x) => (typeof x === 'string' ? fn(x) : x && typeof x === 'object' ? mapObj(x, fn) : x));
      r = JSON.stringify(arr) !== JSON.stringify(v) ? arr : undefined;
    } else if (v && typeof v === 'object') { const sub = transform(v, fn); r = Object.keys(sub).length ? sub : undefined; }
    if (r !== undefined) { out[k] = r; changed = true; }
  }
  return out;
}
function mapObj(o, fn) { return Object.fromEntries(Object.entries(o).map(([k, v]) => [k, typeof v === 'string' ? fn(v) : v])); }

const US = [[/organisation/g, 'organization'], [/Organisation/g, 'Organization'], [/licences/g, 'licenses'], [/licence/g, 'license'], [/Licences/g, 'Licenses'], [/personalise/g, 'personalize'], [/honour/g, 'honor'], [/programmes/g, 'programs'], [/programme/g, 'program'], [/Centre/g, 'Center'], [/centre/g, 'center'], [/catalogues/g, 'catalogs'], [/authorised/g, 'authorized'], [/Authorised/g, 'Authorized'], [/behavioural/g, 'behavioral'], [/colour/g, 'color'], [/analyse/g, 'analyze']];
const us = transform(rd('messages/en.json'), (s) => US.reduce((a, [re, rep]) => a.replace(re, rep), s));
const meta = (o, note) => ({ _meta: { generated: true, note }, ...o });
fs.writeFileSync(path.join(root, 'messages/overrides/en-US.json'), JSON.stringify(meta(us, 'Generated by scripts/gen-overrides.mjs – British→US spelling'), null, 2) + '\n');
const ch = transform(rd('messages/de.json'), (s) => s.replace(/ß/g, 'ss'));
fs.writeFileSync(path.join(root, 'messages/overrides/de-CH.json'), JSON.stringify(meta(ch, 'Generated by scripts/gen-overrides.mjs – Swiss German spelling (ß→ss)'), null, 2) + '\n');
console.log('overrides written:', Object.keys(us).length, 'en-US namespaces,', Object.keys(ch).length, 'de-CH namespaces');
